/**
 * 日本鐵道「路線＋車站＋徒步時間」共用正則片段。
 *
 * 這裡是全站唯一的交通文字樣式來源。過去 transitParser.ts 與
 * rentalListingReconciliation.ts 各自維護一份幾乎相同但細節不一致的巨大正則，
 * 結果只改一邊就會產生「某些圖紙第二條路線整條消失」的靜默漏失。
 *
 * 設計要點：
 * 1. 站名一律用「非貪婪 + 長度上限」收斂，**不可**把「徒」「歩」放進排除集。
 *    日本有御徒町／新御徒町／仲御徒町等含「徒」的正式站名，排除字元會讓整列解析不出來。
 *    防止站名吃掉後方「徒歩」的正確手段是讓 WALK 片段自己當終止符並由引擎回溯。
 * 2. 部分路線的愛稱本身就是完整路線名、後面不接「線」（如ゆりかもめ、江ノ電），
 *    必須列在 STANDALONE_LINE，否則「營運商＋後綴」的組合永遠匹配不到。
 */

/** 條目開頭常見的裝飾符號（◎●◆■※・）。 */
export const BULLET = String.raw`[◎●◆■※・\s]*`;

/** 站名／路線名不可能包含的分隔字元（引號、括號、斜線）。注意：刻意不含「徒」「歩」。 */
const BREAK_CHARS = String.raw`\s\n／/「」『』《》〈〉【】\[\]［］〔〕〖〗〘〙`;

/** 鐵道營運商前綴。放在最後的通用段落用非貪婪＋長度上限，避免災難性回溯。 */
const OPERATOR = String.raw`(?:JR東日本|JR東海|JR西日本|JR|東京メトロ|東京都交通局|都営地下鉄|都営|東急|京王|小田急|西武|東武|京急|京成|相鉄|相鉄・JR直通|横浜市営地下鉄|埼玉高速鉄道|東京臨海高速鉄道|首都圏新都市鉄道|つくば|ゆりかもめ|りんかい|名鉄|近鉄|阪急|阪神|南海|京阪|北大阪急行|泉北高速|神戸市営地下鉄|札幌市営地下鉄|仙台市営地下鉄|福岡市営地下鉄|[^${BREAK_CHARS}駅]{1,20}?)`;

/** 列車種別：常黏在「線」後面且不帶空格（如「中央・総武線各停」）。 */
const TRAIN_TYPE = String.raw`(?:各停|各駅停車|各駅|快速急行|特別快速|通勤快速|通勤準急|区間急行|区間準急|新快速|特快|快速|急行|準急|特急|普通|緩行線|直通)`;

/** 路線名後綴。`線` 之後允許緊接列車種別。 */
const LINE_SUFFIX = String.raw`(?:線${TRAIN_TYPE}?|ライン|ライナー|トラム|電鉄|電車|地下鉄|メトロ|エクスプレス|モノレール|新交通|JR)`;

/**
 * 自身即為完整路線名、後面不接「線」的愛稱與特例。
 * 必須排在「營運商＋後綴」之前先行嘗試。
 */
const STANDALONE_LINE = String.raw`(?:ゆりかもめ|江ノ電|江ノ島電鉄|日暮里・舎人ライナー|舎人ライナー|さくらトラム|シーサイドライン|つくばエクスプレス)`;

/** 路線名整體（含尾端括號註記，如「(直通)」「（各停）」）。 */
export const LINE = String.raw`(?:${STANDALONE_LINE}|${OPERATOR}${LINE_SUFFIX})(?:\([^)]{1,20}\)|（[^）]{1,20}）)?`;

/** 路線與站名之間的分隔（空格、斜線、中點或開引號）。 */
export const LINE_STATION_GAP = String.raw`[\s／/・「『【\[［]+`;

/**
 * 車站名。非貪婪且長度上限 12（日本最長正式站名約 12 字），
 * 讓後續 WALK 片段透過回溯決定邊界；不排除「徒」「歩」。
 */
export const STATION = String.raw`[^${BREAK_CHARS}駅]{1,12}?`;

/** 站名後可能出現的收尾引號。 */
export const STATION_CLOSE = String.raw`[」』】\]］]?`;

/** 「（駅）（より）徒歩 N 分」。捕獲 1 組：分鐘數。 */
export const WALK = String.raw`(?:駅)?\s*(?:より|から)?\s*(?:徒歩|歩)\s*(\d{1,3})\s*分`;

/** 句型 A：路線 + 車站 + 徒步。捕獲：1=路線 2=車站 3=分鐘。 */
export const LINE_STATION_WALK = String.raw`(${LINE})${LINE_STATION_GAP}(${STATION})${STATION_CLOSE}${WALK}`;

/** 句型 B：僅車站 + 徒步（無路線前綴）。捕獲：1=車站 2=分鐘。 */
export const STATION_WALK = String.raw`[「『【\[［]?(${STATION})${STATION_CLOSE}${WALK}`;

/**
 * 不是車站的常見誤抓來源。
 *
 * 這份清單只能收「絕不可能出現在站名裡」的詞。
 * 許多設施名其實是正式站名的一部分，誤列會把正常車站整個擋掉：
 *   公園 → 戸田公園・葛西臨海公園・お台場海浜公園
 *   高校 → 鎌倉高校前
 *   大学 → 都立大学・学芸大学・羽沢横浜国大
 *   病院 → ○○病院前（路面電車）
 *   役所 → 市役所前（路面電車）
 * 因此上述詞彙一律不得加入本清單。
 */
const NON_STATION = /バス停|停留所|バスのりば|バス乗り場|コンビニ|スーパー|ドラッグ|薬局|幼稚園|保育園|ｺﾝﾋﾆ/u;

/**
 * 句尾助詞殘留（「○○まで徒歩3分」會把「まで」吃進站名）。
 * 刻意只列多字助詞：單字「の」「に」「へ」可能是站名的一部分
 * （如「ひばりケ丘」「元町・中華街」等改寫），誤刪會破壞正常站名。
 */
const TRAILING_PARTICLE = /(?:まで|から|より)$/u;

/** 至少要含一個日文字或英數字，否則不可能是站名。 */
const HAS_NAME_CHAR = /[0-9A-Za-z\u3040-\u30FF\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF]/u;

/**
 * 判斷擷取出的 token 是否像車站名。
 * `(?:駅)?` 設為可選後，pattern 會連「コンビニまで徒歩3分」一起收進來，
 * 因此必須在取用前過濾，否則 station 欄位會被非車站文字污染。
 */
export function isPlausibleStationToken(token: string): boolean {
  const value = token.trim();
  if (!value || value.length > 12) return false;
  if (NON_STATION.test(value)) return false;
  if (TRAILING_PARTICLE.test(value)) return false;
  // 必須含實際名稱字元。注意：在 u flag 下 \w 只認 ASCII，
  // 用 /^[\d\W_]+$/u 判斷會把所有日文站名都誤判為「純標點」。
  if (!HAS_NAME_CHAR.test(value)) return false;
  // 純數字不可能是站名。
  if (/^\d+$/u.test(value)) return false;
  return true;
}

/**
 * 同一條路線在圖紙上的常見簡寫 → 標準鍵。
 * 只收錄「確定是同一個服務、同一組月台」的別名；
 * 快速與各停屬於不同月台與不同所要時間，不可列入。
 */
const LINE_ALIASES: Array<[RegExp, string]> = [
  // 中央・総武線各停（緩行）：圖紙常簡寫成「総武線各停」「中央線各停」「総武緩行線」。
  [/^(?:中央)?総武線?(?:各停|各駅停車|各駅|緩行線?)$/u, "中央総武線各停"],
  [/^中央線(?:各停|各駅停車|各駅|緩行線?)$/u, "中央総武線各停"],
  [/^中央総武線(?:各停|各駅停車|各駅|緩行線?)$/u, "中央総武線各停"],
  // 京浜東北線／京浜東北・根岸線。
  [/^京浜東北(?:・根岸)?線$/u, "京浜東北線"],
  // 東武スカイツリーライン＝東武伊勢崎線（同一路線的愛稱）。
  [/^東武(?:スカイツリーライン|伊勢崎線)$/u, "東武伊勢崎線"],
  // 日暮里・舎人ライナー。
  [/^(?:日暮里)?舎人ライナー$/u, "舎人ライナー"],
  // ゆりかもめ＝東京臨海新交通臨海線。
  [/^(?:東京臨海新交通臨海線|ゆりかもめ)$/u, "ゆりかもめ"],
];

/**
 * 路線名正規化鍵：用於「同一條路線的不同寫法」去重。
 *
 * 刻意**保留列車種別**：「中央・総武線各停」與「総武快速線」是不同月台、
 * 不同所要時間的獨立動線，合併會損失使用者真正需要的資訊。
 * 收斂的是營運商前綴、排版差異（空白、中點、引號）與確定同義的路線簡寫。
 */
export function normalizeLineKey(line: string): string {
  const base = (line || "")
    .normalize("NFKC")
    .replace(/^[◎●◆■※・\s]+/u, "")
    .replace(/^(?:JR東日本|JR東海|JR西日本|JR|東日本旅客鉄道)/u, "")
    .replace(/^(?:東京都交通局|都営地下鉄)/u, "都営")
    .replace(/^(?:東京地下鉄)/u, "東京メトロ")
    .replace(/[\s\u3000・･（）()「」『』【】]/gu, "");

  for (const [pattern, canonical] of LINE_ALIASES) {
    if (pattern.test(base)) return canonical.toLowerCase();
  }
  return base.toLowerCase();
}
