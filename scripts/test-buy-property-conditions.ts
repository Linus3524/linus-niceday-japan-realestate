import assert from 'node:assert/strict';
import {buyPropertyRules,sanitizeBuyPropertyConditions,validateBuyRequirement} from '../src/lib/findHome/buySchema';
import {requirementText} from '../src/lib/findHome/lead';
const options=(types:string[])=>buyPropertyRules(types).options.map(option=>option.id);
assert.ok(options(['house']).includes('parking'));
assert.ok(options(['house']).includes('two-toilets'));
assert.ok(!options(['house']).includes('elevator'));
assert.ok(!options(['house']).includes('autolock'));
assert.ok(!options(['house']).includes('pets'));
assert.ok(options(['condo']).includes('elevator'));
assert.ok(options(['building']).includes('elevator'));
assert.deepEqual(options(['land']),['vacant-land','no-building-condition','regular-plot','freehold']);
assert.ok(options(['house','condo']).includes('two-toilets'));
assert.ok(options(['house','condo']).includes('elevator'));
const old={propertyTypes:['land'],mustHaves:['elevator','autolock','parking','two-toilets','freehold','vacant-land'],layouts:['2LDK'],floorMin:'3',ageMaxYears:'20',structure:'rc'};
const land=sanitizeBuyPropertyConditions(old);
assert.deepEqual(land.mustHaves,['freehold','vacant-land']);
assert.deepEqual(land.layouts,[]);
assert.ok(!buyPropertyRules(['land']).adjustableOptions.some(option=>option.id==='age'));
assert.equal(land.floorMin,'');assert.equal(land.ageMaxYears,'0');assert.equal(land.structure,undefined);
const house=sanitizeBuyPropertyConditions({...old,propertyTypes:['house']});
assert.deepEqual(house.mustHaves,['parking','two-toilets','freehold']);
assert.equal(house.floorMin,'');assert.equal(house.ageMaxYears,'20');
const parsed=validateBuyRequirement({...old,floorMin:'not a number',ageMaxYears:'not a number'},2);
assert.equal(parsed.errors.floorMin,undefined);assert.equal(parsed.errors.ageMaxYears,undefined);
assert.deepEqual(parsed.value.mustHaves,['freehold','vacant-land']);
const data=validateBuyRequirement({...old,propertyTypes:['house'],mustHaves:['two-toilets','parking']},2).value;
const text=requirementText(null,data);
assert.match(text,/兩間以上廁所/);assert.match(text,/停車位/);
console.log('Buy property rules passed: house parking / two toilets, condo amenities, land fields, mixed types and stale API values');
